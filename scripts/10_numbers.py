MODELS = ["decision_tree", "random_forest", "extra_trees", "xgboost", "lightgbm"]
MODEL_LABEL = {"decision_tree": "DT", "random_forest": "RF", "extra_trees": "ET",
               "xgboost": "XGBoost", "lightgbm": "LightGBM"}
PROTOCOLS = ["random", "random_dedup", "file_grouped", "order_within_file"]
SCHEMES = ["L8", "L34", "LM", "L2"]


def clean(key: str) -> str:
    return re.sub(r"[^A-Za-z0-9-]", "", key.replace("_", ""))


def integer(n: float) -> str:
    return f"{int(round(n)):,}".replace(",", "{,}")


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}"


def dec(x: float, digits: int = 3) -> str:
    return f"{x:.{digits}f}"


def leaders(col: pd.Series, fmt: Callable[[float], str]) -> str:
    """Every model whose value prints the same as the best one ("LightGBM and XGBoost"), so a
    tie at the printed precision is never reported as one winner."""
    top = fmt(col.max())
    names = [MODEL_LABEL.get(m, m) for m in col.index if fmt(col[m]) == top]
    return names[0] if len(names) == 1 else ", ".join(names[:-1]) + " and " + names[-1]


def tex_text(s: str) -> str:
    return s.replace("_", r"\_").replace("&", r"\&").replace("%", r"\%")


class Numbers:
    def __init__(self) -> None:
        self.rows: list[dict[str, str]] = []
        self.keys: set[str] = set()

    def add(self, key: str, value: str, source: str, how: str) -> None:
        key = clean(key)
        if key in self.keys:
            raise ValueError(f"duplicate key {key}")
        self.keys.add(key)
        self.rows.append({"key": key, "value": value, "source": source, "how": how})

    def tex(self, header: str) -> str:
        out = [f"% {header}", "% generated by scripts/10_numbers.py; do not edit by hand",
               r"\makeatletter",
               r"\providecommand{\val}[1]{\ifcsname val@#1\endcsname"
               r"\csname val@#1\endcsname\else\textbf{??#1??}\fi}"]
        for r in self.rows:
            out.append(f"\\expandafter\\def\\csname val@{r['key']}\\endcsname{{{r['value']}}}")
        out += [r"\makeatother", ""]
        return "\n".join(out)


GROUPS: list[Callable[[Numbers, str], None]] = []


def group(fn: Callable[[Numbers, str], None]) -> Callable[[Numbers, str], None]:
    GROUPS.append(fn)
    return fn


def load(path: str) -> Any:
    p = project_path(path)
    if not p.exists():
        raise FileNotFoundError(path)
    return json.loads(p.read_text(encoding="utf-8"))


