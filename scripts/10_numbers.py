@group
def splits(n: Numbers, profile: str) -> None:
    for p in PROTOCOLS:
        found = sorted(project_path("results/splits").glob(f"{p}_s*.json"),
                       key=lambda f: int(f.stem.rsplit("_s", 1)[1]))
        if not found:
            continue
        s = json.loads(found[0].read_text(encoding="utf-8"))
        src = str(found[0].relative_to(project_path("."))).replace("\\", "/")
        for part in ["train", "val", "test", "unused"]:
            n.add(f"split-{p}-{part}", integer(s["rows"][part]), src, f"rows.{part}")
        purged = s.get("purged_rows_seen_in_train")
        if isinstance(purged, dict):
            total_eval = s["rows"]["val"] + s["rows"]["test"] + sum(purged.values())
            n.add(f"split-{p}-purged", integer(sum(purged.values())), src,
                  "validation + test rows removed because their vector is in training")
            n.add(f"split-{p}-purged-share", pct(sum(purged.values()) / total_eval), src,
                  "purged / (val + test + purged), %")


@group
def test_ceilings(n: Numbers, profile: str) -> None:
    """Label-conflict ceiling of the rows each protocol tests on (05_split_ceilings.py), and
    how far the most accurate model stays below it."""
    path = "results/splits/test_ceilings" + ("" if profile == "full" else f"_{profile}") + ".csv"
    if not project_path(path).exists():
        raise FileNotFoundError(path)
    c = pd.read_csv(project_path(path))
    agg = c.groupby(["scheme", "protocol"])["accuracy_ceiling"].agg(["mean", "count"])
    r = _runs(profile)
    main = r[(r["train_mode"] == "capped") & r["params_mode"].isin(["tuned", "tuned_from_random"])
             & r["model"].isin(MODELS)]
    acc = main.groupby(["scheme", "protocol", "model"])["accuracy"].mean()
    for (s, p), row in agg.iterrows():
        # a ceiling below 100% is never printed as 100.00
        shown = "more than 99.99" if 0.99995 <= row["mean"] < 1 else pct(row["mean"], 2)
        n.add(f"tceil-{s}-{p}", shown, path,
              "accuracy ceiling of the test part, mean over seeds, %")
        n.add(f"tceil-{s}-{p}-seeds", str(int(row["count"])), path, "seeds with a saved split")
        if (s, p) in acc.index.droplevel(2):
            best = acc.loc[(s, p)].max()
            n.add(f"tgap-{s}-{p}", f"{100 * (row['mean'] - best):.1f}",
                  f"{path}; results/experiments/**/*_{profile}.json",
                  "test-part ceiling minus the highest mean accuracy of the five models, "
                  "percentage points")


