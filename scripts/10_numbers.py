    parser.add_argument("--profile", choices=["quick", "full"], required=True)
    args = parser.parse_args()
    log = get_logger(f"10_numbers_{args.profile}", project_path("logs"))
    nums = Numbers()
    for fn in GROUPS:
        before = len(nums.rows)
        try:
            fn(nums, args.profile)
            log.info("%s: %d values", fn.__name__, len(nums.rows) - before)
        except FileNotFoundError as err:
            del nums.rows[before:]
            nums.keys = {r["key"] for r in nums.rows}
            log.info("%s skipped: missing %s", fn.__name__, err)
