def _main_means(profile: str) -> pd.DataFrame:
    """Mean macro-F1 per protocol, scheme and model of the main runs (capped, tuned)."""
    r = _runs(profile)
    r = r[(r["train_mode"] == "capped") & r["params_mode"].isin(["tuned", "tuned_from_random"])
          & r["protocol"].isin(PROTOCOLS) & r["model"].isin(MODELS)]
    return r.groupby(["protocol", "scheme", "model"])["macro_f1"].mean().reset_index()


@group
def analysis_summary(n: Numbers, profile: str) -> None:
    """Summary values for the findings of Step 7. The rules were fixed before the full results
    existed (D-037): a difference counts at ALPHA after the Holm correction; an interval is
    compared with the distance between the best and the worst model of its block; confidence
    is compared with accuracy; the SHAP share of the leading features; the cheapest and the
    dearest model for each cost."""
    out = _analysis(profile)
    rel = str(out.relative_to(project_path("."))).replace("\\", "/")
    here = "scripts/10_numbers.py"
    comp_path = out / "model_comparison.json"
    if not comp_path.exists():
        raise FileNotFoundError(f"{rel}/model_comparison.json")
    src = f"{rel}/model_comparison.json"
    comp = json.loads(comp_path.read_text(encoding="utf-8"))
    n.add("stat-alpha", f"{ALPHA:g}", here, "ALPHA: level of the Holm-adjusted tests")
    tested = 0
    for g, c in comp.items():
        ps = [w["p_holm"] for w in c["wilcoxon_vs_best"]]
        ranks = c["mean_ranks"]
        order = sorted(ranks, key=lambda m: ranks[m])
        n.add(f"holm-n-{g}", str(len(ps)), src, "models compared with the best")
        n.add(f"holm-sig-n-{g}", str(sum(x < ALPHA for x in ps)), src,
              "models that differ from the best at ALPHA after Holm")
        n.add(f"holm-min-{g}", f"{min(ps):.2g}", src, "smallest Holm-adjusted p")
        n.add(f"rank-second-{g}", MODEL_LABEL[order[1]], src, "second by mean rank")
        n.add(f"rank-worst-{g}", MODEL_LABEL[order[-1]], src, "last by mean rank")
        n.add(f"rank-gap-{g}", dec(ranks[order[1]] - ranks[order[0]], 2), src,
              "mean rank of the second minus the best")
        tested += "friedman_p" in c
    n.add("friedman-n", str(tested), src, "groups with a Friedman test")
    n.add("friedman-sig-n", str(sum(c.get("friedman_p", 1.0) < ALPHA for c in comp.values())),
          src, "groups whose Friedman test is below ALPHA")
    if profile == "full":
        # The Results text says: LightGBM has the best mean rank in every group, the Friedman
        # test is below ALPHA in every group, and over all blocks LightGBM differs from DT, ET
        # and RF but not from XGBoost. Stop if that changes.
        assert all(c["best"] == "lightgbm" for c in comp.values()), {g: c["best"] for g, c in
                                                                       comp.items()}
        assert all(c.get("friedman_p", 1.0) < ALPHA for c in comp.values())
        sig = {w["model"] for w in comp["all"]["wilcoxon_vs_best"] if w["p_holm"] < ALPHA}
        assert sig == {"decision_tree", "extra_trees", "random_forest"}, sig

    ci = out / "bootstrap_ci.csv"
    if ci.exists() and ci.stat().st_size > 5:
        src = f"{rel}/bootstrap_ci.csv"
        b = pd.read_csv(ci)
        b["width"] = b["ci_high"] - b["ci_low"]
        means = _main_means(profile)
        blocks = []
        for (proto, scheme), sub in b.groupby(["protocol", "scheme"]):
            m = means[(means["protocol"] == proto) & (means["scheme"] == scheme)]
            m = m[m["model"].isin(sub["model"])].set_index("model")["macro_f1"]
            if len(m) < 2:
                continue
            by = sub.set_index("model")
            ranked = m.sort_values(ascending=False).index
            best, second, worst = ranked[0], ranked[1], ranked[-1]
            blocks.append({
                "protocol": proto, "scheme": scheme, "best": best,
                "width": by.loc[best, "width"], "spread": m[best] - m[worst],
                "overlap_second": (by.loc[best, "ci_low"] <= by.loc[second, "ci_high"])
                and (by.loc[second, "ci_low"] <= by.loc[best, "ci_high"]),
                "above_worst": by.loc[best, "ci_low"] > by.loc[worst, "ci_high"]})
        k = pd.DataFrame(blocks)
        if not k.empty:
            def where(row: pd.Series) -> str:
                return f"{SCHEME_WORD[row['scheme']]}, {PROTOCOL_WORD[row['protocol']]} split"
            lo, hi = k.loc[k["width"].idxmin()], k.loc[k["width"].idxmax()]
            n.add("ci-blocks", str(len(k)), src, "blocks of protocol and scheme with intervals")
            n.add("ciw-min", dec(lo["width"]), src, "narrowest interval of a best model")
            n.add("ciw-min-where", where(lo), src, "its block")
            n.add("ciw-max", dec(hi["width"]), src, "widest interval of a best model")
            n.add("ciw-max-where", where(hi), src, "its block")
            n.add("ciw-wider-than-spread-n", str(int((k["width"] > k["spread"]).sum())), src,
                  "blocks whose interval of the best model is wider than best minus worst model")
            n.add("ci-overlap-second-n", str(int(k["overlap_second"].sum())), src,
                  "blocks where the intervals of the best and the second model overlap")
            if profile == "full":
                # The Results text says this holds in every block.
                assert bool(k["overlap_second"].all()), k[~k["overlap_second"]].to_dict()
            n.add("ci-above-worst-n", str(int(k["above_worst"].sum())), src,
                  "blocks where the interval of the best model lies above that of the worst")
            for proto, sub in k.groupby("protocol"):
                n.add(f"ciw-mean-{proto}", dec(sub["width"].mean()), src,
                      "mean interval width of the best model over the label schemes")

    cal = out / "calibration.csv"
    if cal.exists() and cal.stat().st_size > 5:
        src = f"{rel}/calibration.csv"
        c = pd.read_csv(cal)
        c["over"] = c["mean_confidence"] - c["accuracy"]
        for row in c.itertuples():
            n.add(f"over-{row.protocol}-{row.scheme}-{row.model}", f"{row.over * 100:.1f}", src,
                  "mean confidence minus accuracy, points")
        n.add("cal-n", str(len(c)), src, "configurations with saved confidence")
        n.add("cal-over-n", str(int((c["over"] > 0).sum())), src,
              "configurations whose mean confidence is above their accuracy")
        over_l8 = c[c["scheme"] == "L8"].groupby("protocol")["over"].apply(lambda v: (v > 0).sum())
        for proto, count in over_l8.items():
            n.add(f"cal-over-n-L8-{proto}", str(int(count)), src,
                  "models whose mean confidence is above their accuracy, eight families")
        if profile == "full":
            # The Results text says: only under the file-grouped protocol are most models more
            # confident than accurate, and none is on the random split. Stop if that changes.
            others = over_l8.drop("file_grouped")
            assert over_l8["file_grouped"] > others.max() and over_l8["random"] == 0, \
                over_l8.to_dict()
            assert over_l8["file_grouped"] > (c["scheme"] == "L8").sum() / len(over_l8) / 2
        l8 = c[c["scheme"] == "L8"]
        if not l8.empty:
            per_model = l8.groupby("model")["ece"].mean().sort_values()
            n.add("ece-best-L8", MODEL_LABEL[per_model.index[0]], src,
                  "lowest mean ECE over the protocols, eight families")
            n.add("ece-best-L8-value", dec(per_model.iloc[0]), src, "its mean ECE")
            n.add("ece-worst-L8", MODEL_LABEL[per_model.index[-1]], src, "highest mean ECE")
            n.add("ece-worst-L8-value", dec(per_model.iloc[-1]), src, "its mean ECE")
            for m, v in per_model.items():
                n.add(f"ece-mean-L8-{m}", dec(v), src, "mean ECE over the protocols")
            worst = l8.loc[l8["over"].idxmax()]
            n.add("over-max-L8", f"{worst['over'] * 100:.1f}", src,
                  "largest excess of confidence over accuracy, eight families, points")
            n.add("over-max-L8-where",
                  f"{MODEL_LABEL[worst['model']]}, {PROTOCOL_WORD[worst['protocol']]} split", src,
                  "its model and protocol")

    shap = out / "shap_overall.csv"
    if shap.exists():
        src = f"{rel}/shap_overall.csv"
        s = pd.read_csv(shap, index_col=0).iloc[:, 0].sort_values(ascending=False)
        n.add("shap-features-n", str(len(s)), src, "features ranked")
        n.add("shap-top1-share", pct(s.iloc[0] / s.sum()), src,
              "share of the first feature in the sum of mean |SHAP|, %")
        n.add("shap-top5-share", pct(s.iloc[:5].sum() / s.sum()), src,
              "share of the first five features, %")

    cost = out / "cost.csv"
    if cost.exists():
        src = f"{rel}/cost.csv"
        c = pd.read_csv(cost).set_index("model")
        multi = [col for col in c.columns
                 if col.startswith("batch_us_per_row_") and col != "batch_us_per_row_1thr"]
        measures = [("ms", "single_row_median_ms_1thr", "time to label one row, 1 thread"),
                    ("mb", "file_mb", "model file size"),
                    ("fit", "fit_seconds", "training time"),
                    ("us", "batch_us_per_row_1thr", "batch time per row, 1 thread")]
        for short, col, what in measures:
            lo, hi = c[col].idxmin(), c[col].idxmax()
            n.add(f"cost-{short}-lowest", MODEL_LABEL[lo], src, f"lowest {what}")
            n.add(f"cost-{short}-highest", MODEL_LABEL[hi], src, f"highest {what}")
            n.add(f"cost-{short}-ratio", f"{c.loc[hi, col] / c.loc[lo, col]:.0f}", src,
                  f"highest over lowest {what}")
        for m in c.index:
            n.add(f"cost-rps-{m}", integer(1e6 / c.loc[m, "batch_us_per_row_1thr"]), src,
                  "rows per second in batches, 1 thread")
            if multi:
                n.add(f"cost-speedup-{m}",
                      f"{c.loc[m, 'batch_us_per_row_1thr'] / c.loc[m, multi[0]]:.1f}", src,
                      f"batch time with 1 thread over {multi[0].rsplit('_', 1)[1]}")
        if multi:
            n.add("cost-threads", multi[0].rsplit("_", 1)[1].removesuffix("thr"), src,
                  "threads of the multi-thread measurement")
        if {"lightgbm", "xgboost"} <= set(c.index):
            ratio = (c.loc["lightgbm", "batch_us_per_row_1thr"]
                     / c.loc["xgboost", "batch_us_per_row_1thr"])
            n.add("cost-lgbm-over-xgb-batch", f"{ratio:.0f}", src,
                  "LightGBM batch time per row over XGBoost's, 1 thread")
        if profile == "full":
            # The Results text says: DT is cheapest on every measure, XGBoost trains longest,
            # ET makes the largest file, LightGBM is slowest in batches but faster than RF, ET
            # and XGBoost on one row, and every model except LightGBM labels at least a
            # thousand rows per second on one thread. Stop if that changes.
            for _, col, _ in measures:
                assert c[col].idxmin() == "decision_tree", col
            assert c["fit_seconds"].idxmax() == "xgboost"
            assert c["file_mb"].idxmax() == "extra_trees"
            assert c["batch_us_per_row_1thr"].idxmax() == "lightgbm"
            one = c["single_row_median_ms_1thr"]
            assert all(one["lightgbm"] < one[m]
                       for m in ("random_forest", "extra_trees", "xgboost"))
            rps = 1e6 / c["batch_us_per_row_1thr"]
            assert rps.drop("lightgbm").min() >= 1000 > rps["lightgbm"], rps.to_dict()


def script_constant(path: str, name: str) -> Any:
    """Value of a module-level constant `NAME = literal` in one of our scripts, read without
    running the script."""
    tree = ast.parse(project_path(path).read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(f"{name} not found in {path}")


