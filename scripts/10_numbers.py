UNSEEN_OWN = 0.9     # a held-out type is "placed in its own family" at or above this share
UNSEEN_MISSED = 0.5  # ... and "mostly placed elsewhere" below this share
UNSEEN_TOP = 3       # held-out types with the largest loss that are named


@group
def unseen(n: Numbers, profile: str) -> None:
    """Unseen-type test (RQ2). Every share is compared with the share of the same type when it
    is in training (deduplicated split, same model and seeds), because some types are placed
    outside their family even then. Rule (D-036): a type loses when its share falls by more
    than RECALL_LOSS against that reference; the UNSEEN_TOP largest losses are named."""
    from iotml.results import seen_family_mix

    r = _runs(profile)
    r = r[r["protocol"].str.startswith("unseen_type__") & (r["scheme"] == "L8")]
    if r.empty or "held_out" not in r:
        raise FileNotFoundError("unseen-type runs")
    # one model, the same as Figure 13 and Table 13 (XGBoost in the paper)
    model = "xgboost" if (r["model"] == "xgboost").any() else r["model"].iloc[0]
    r = r[r["model"] == model]
    src = f"results/experiments/unseen_type__*/L8/{model}/*_{profile}.json"
    n.add("unseen-model", MODEL_LABEL.get(model, model), src, "model of the unseen-type runs")
    share = r.groupby("held_out")["held_out_recall_own_class"].mean()
    for label, v in share.items():
        n.add(f"unseen-{label}", dec(v, 2), src, "share of held-out rows given own family")
    n.add("unseen-types", str(len(share)), src, "held-out types run")
    n.add("unseen-median", dec(share.median(), 2), src, "median share")
    n.add("unseen-below05", str(int((share < UNSEEN_MISSED).sum())), src, "types under 0.5")
    n.add("unseen-above09", str(int((share >= UNSEEN_OWN).sum())), src, "types at or above 0.9")

    # where the rows of each held-out type go (mean over its seeds)
    family: dict[str, str] = {}
    mixes: dict[str, list[pd.Series]] = {}
    for _, row in r.iterrows():
        u = json.loads(Path(row["path"]).read_text(encoding="utf-8"))["metrics"]["unseen_type"]
        family[u["held_out"]] = u["own_class"]
        mixes.setdefault(u["held_out"], []).append(pd.Series(u["predicted_as"], dtype=float))
    mix = pd.DataFrame({k: pd.concat(v, axis=1).fillna(0.0).mean(axis=1)
                        for k, v in mixes.items()}).T.fillna(0.0)
    benign = mix["Benign"] if "Benign" in mix else pd.Series(0.0, index=mix.index)
    others = {k: mix.loc[k].drop(family[k], errors="ignore") for k in share.index}

    # the same types when they are in training
    seeds = sorted(int(s) for s in r["seed"].unique())
    seen_mix = seen_family_mix(profile, model, seeds).loc[share.index]
    seen = pd.Series({k: seen_mix.loc[k, family[k]] for k in share.index})
    src_seen = (f"data/interim/predictions/random_dedup/L8/{model}/"
                f"capped_tuned_from_random_s*_{profile}.npz")
    loss = seen - share
    n.add("unseen-loss-points", f"{RECALL_LOSS * 100:.0f}", "scripts/10_numbers.py",
          "RECALL_LOSS: a type loses when its own-family share falls by more than this, points")
    n.add("unseen-seen-median", dec(seen.median(), 2), src_seen,
          "median own-family share of the same types when they are in training")
    n.add("unseen-seen-below05", str(int((seen < UNSEEN_MISSED).sum())), src_seen,
          "types under 0.5 even when in training")
    n.add("unseen-seen-above09", str(int((seen >= UNSEEN_OWN).sum())), src_seen,
          "types at or above 0.9 when in training")
    n.add("unseen-loss-n", str(int((loss > RECALL_LOSS).sum())), src,
          "types whose own-family share falls by more than RECALL_LOSS when held out")
    n.add("unseen-gain-n", str(int((loss < -RECALL_LOSS).sum())), src,
          "types whose own-family share rises by more than RECALL_LOSS when held out")
    n.add("unseen-same-n", str(int((loss.abs() <= RECALL_LOSS).sum())), src,
          "types whose own-family share moves by at most RECALL_LOSS")
    n.add("unseen-loss-median", f"{loss.median() * 100:.1f}", src,
          "median fall of the own-family share, points")
    for label in share.index:
        n.add(f"unseen-seen-{label}", dec(seen[label], 2), src_seen,
              "own-family share when the type is in training")
        n.add(f"unseen-loss-{label}", f"{loss[label] * 100:.1f}", src,
              "in training minus held out, points")
        n.add(f"unseen-benign-{label}", pct(benign[label]), src,
              "held-out rows called benign, %")
        n.add(f"unseen-seen-benign-{label}", pct(seen_mix.loc[label, "Benign"]), src_seen,
              "rows called benign when the type is in training, %")
    for i, label in enumerate(loss.sort_values(ascending=False).index[:UNSEEN_TOP], start=1):
        n.add(f"unseen-loss-top{i}", tex_text(label), src, "type with the largest fall")
        n.add(f"unseen-loss-top{i}-family", family[label], src, "its family")
        n.add(f"unseen-loss-top{i}-from", pct(seen[label]), src_seen, "share in training, %")
        n.add(f"unseen-loss-top{i}-to", pct(share[label]), src, "share held out, %")
        n.add(f"unseen-loss-top{i}-other", str(others[label].idxmax()), src,
              "family that takes most of the rest")
        n.add(f"unseen-loss-top{i}-othershare", pct(others[label].max()), src, "its share, %")
    # per family: how many types, mean shares, how many lose
    by_family: dict[str, list[str]] = {}
    for label in share.index:
        by_family.setdefault(family[label], []).append(label)
    for fam, k in sorted(by_family.items()):
        n.add(f"unseen-fam-n-{fam}", str(len(k)), src, "held-out types of this family")
        n.add(f"unseen-fam-{fam}", dec(share[k].mean(), 2), src, "mean share held out")
        n.add(f"unseen-famseen-{fam}", dec(seen[k].mean(), 2), src_seen, "mean share in training")
        n.add(f"unseen-fam-loss-n-{fam}", str(int((loss[k] > RECALL_LOSS).sum())), src,
              "types of this family that lose more than RECALL_LOSS")
    # two groups the Results text names: the fragmentation attacks and the DoS floods
    frag = [k for k in share.index if "Fragmentation" in k]
    dos = by_family.get("DoS", [])
    if frag:
        n.add("unseen-frag-n", str(len(frag)), src, "held-out fragmentation attacks")
        n.add("unseen-frag-loss-n", str(int((loss[frag] > RECALL_LOSS).sum())), src,
              "of these, types that lose more than RECALL_LOSS")
        n.add("unseen-frag-min", dec(share[frag].min(), 2), src,
              "lowest own-family share of a held-out fragmentation attack")
    if dos:
        to_ddos = [float(mix.loc[k].get("DDoS", 0.0)) for k in dos]
        n.add("unseen-dos-to-ddos-min", pct(min(to_ddos)), src,
              "lowest share of the rows of a held-out DoS type given to DDoS, %")
    if profile == "full":
        # The Results text says: no type gains, the fragmentation attacks keep their family,
        # and every DoS type moves to DDoS. Stop if the data no longer says that.
        assert int((loss < -RECALL_LOSS).sum()) == 0, loss.sort_values().head(3).to_dict()
        assert frag and bool((loss[frag] <= RECALL_LOSS).all()), loss[frag].to_dict()
        # (the text quotes the lowest share itself, key unseen-dos-to-ddos-min)
        assert dos and min(to_ddos) > 0.5, dict(zip(dos, to_ddos, strict=True))
    # how many held-out types send most of the rest to each family
    top_other = pd.Series({k: o.idxmax() for k, o in others.items() if o.max() > 0})
    for fam, count in top_other.value_counts().items():
        n.add(f"unseen-other-n-{fam}", str(int(count)), src,
              "held-out types whose largest other family this is")
    # an attack called benign is a missed attack
    n.add("unseen-benign-n", str(int((benign > RECALL_LOSS).sum())), src,
          "held-out types with more than RECALL_LOSS of their rows called benign")
    n.add("unseen-seen-benign-n", str(int((seen_mix["Benign"] > RECALL_LOSS).sum())), src_seen,
          "the same count when the types are in training")
    n.add("unseen-benign-max-label", tex_text(str(benign.idxmax())), src,
          "held-out type with the largest benign share")
    n.add("unseen-benign-max", pct(benign.max()), src, "that share, %")
    n.add("unseen-benign-max-seen", pct(seen_mix.loc[benign.idxmax(), "Benign"]), src_seen,
          "benign share of that type when it is in training, %")


