"""Step 10: every number quoted in the paper, as LaTeX macros with a source trace.

Usage: python scripts/10_numbers.py --profile full|quick

Writes paper/numbers.tex (or paper/numbers_quick.tex), which defines \\val{key} for each value,
and results/number_trace.csv (or results/number_trace_quick.csv) with the key, the printed
value, the file it came from and how it was computed. The text of the paper uses \\val{key}
only; a key that is not defined prints as a bold ??key?? marker, and scripts/11_check_paper.py
fails on it. Groups whose inputs do not exist yet are skipped.
"""

