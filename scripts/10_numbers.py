@group
def main_results(n: Numbers, profile: str) -> None:
    r = _runs(profile)
    src = f"results/experiments/**/*_{profile}.json"
    main = r[(r["train_mode"] == "capped") & r["params_mode"].isin(["tuned", "tuned_from_random"])
             & r["protocol"].isin(PROTOCOLS) & r["model"].isin(MODELS)]
    metrics = ["macro_f1", "accuracy", "balanced_accuracy", "mcc", "macro_fpr"]
    agg = main.groupby(["scheme", "protocol", "model"])[metrics].agg(["mean", "std", "count"])
    short = {"macro_f1": "f1", "accuracy": "acc", "balanced_accuracy": "bacc", "mcc": "mcc",
             "macro_fpr": "fpr"}
    for (s, p, m), row in agg.iterrows():
        for metric in metrics:
            k = f"{short[metric]}-{s}-{p}-{m}"
            mean, sd = row[(metric, "mean")], row[(metric, "std")]
            digits = 4 if metric == "macro_fpr" else 3
            n.add(k, dec(mean, digits), src, f"mean {metric} over seeds, capped tuned")
            n.add(f"{k}-sd", dec(sd, digits) if np.isfinite(sd) else "n/a", src, "sd")
        n.add(f"seeds-{s}-{p}-{m}", str(int(row[("macro_f1", "count")])), src, "seeds")
        n.add(f"accpct-{s}-{p}-{m}", pct(row[("accuracy", "mean")], 2), src,
              "mean accuracy over seeds, %, capped tuned")
        uw = main[(main["scheme"] == s) & (main["protocol"] == p) & (main["model"] == m)]
        if uw["unweighted_macro_f1"].notna().any():
            n.add(f"uwf1-{s}-{p}-{m}", dec(uw["unweighted_macro_f1"].mean()), src,
                  "mean macro-F1 on the capped test sample without natural-mix weights")
    f1 = agg[("macro_f1", "mean")]
    for s in SCHEMES:
        if s not in f1.index.get_level_values(0):
            continue
        ref_model = None
        for p in PROTOCOLS:
            if (s, p) not in f1.index.droplevel(2):
                continue
            col = f1.loc[(s, p)]
            best = col.idxmax()
            n.add(f"best-{s}-{p}", leaders(col, dec), src,
                  "model(s) with highest mean macro-F1 (ties at 3 decimals named)")
            n.add(f"bestf1-{s}-{p}", dec(col.max()), src, "its macro-F1")
            n.add(f"spread-{s}-{p}", dec(col.max() - col.min()), src,
                  "best minus worst model, macro-F1")
            acc = agg[("accuracy", "mean")].loc[(s, p)]
            n.add(f"bestacc-{s}-{p}", pct(acc.max(), 2), src, "highest mean accuracy, %")
            n.add(f"bestacc-model-{s}-{p}", leaders(acc, lambda v: pct(v, 2)), src, "")
            if p == "random":
                ref_model = best
            elif ref_model is not None and (s, p, ref_model) in f1.index:
                base = f1.loc[(s, "random", ref_model)]
                drop = base - f1.loc[(s, p, ref_model)]
                n.add(f"drop-{s}-{p}", dec(drop), src,
                      "macro-F1 under random minus under this protocol, best random model")
                n.add(f"droprel-{s}-{p}", pct(drop / base), src, "relative drop, %")
    # "as published": natural class mix, library defaults (Step 4)
    pub = r[(r["train_mode"] == "natural") & (r["params_mode"] == "default")
            & (r["protocol"] == "random")]
    for (s, m), g in pub.groupby(["scheme", "model"]):
        n.add(f"pub-acc-{s}-{m}", pct(g["accuracy"].mean(), 2), src,
              "natural mix, defaults, random split: mean accuracy %")
        n.add(f"pub-f1-{s}-{m}", dec(g["macro_f1"].mean()), src, "same, macro-F1")
        n.add(f"pub-wf1-{s}-{m}", dec(g["weighted_f1"].mean()), src, "same, weighted F1")
    for s, g in pub.groupby("scheme"):
        means = g.groupby("model")["accuracy"].mean()
        n.add(f"pub-bestacc-{s}", pct(means.max(), 2), src, "best as-published accuracy %")
        n.add(f"pub-bestacc-model-{s}", leaders(means, lambda v: pct(v, 2)), src, "")
        f1s = g.groupby("model")["macro_f1"].mean()
        n.add(f"pub-bestf1-{s}", dec(f1s.max()), src, "best as-published macro-F1")
        n.add(f"pub-bestf1-model-{s}", leaders(f1s, dec), src, "")
        n.add(f"pub-spread-{s}", dec(f1s.max() - f1s.min()), src,
              "as published: best minus worst model, macro-F1")


